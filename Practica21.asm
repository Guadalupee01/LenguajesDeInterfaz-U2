## Índice de Prácticas y Códigos

1. **Hola Mundo sin Irvine32** (`HolaMundoSinIrvine.asm`) - Uso de la API nativa de Windows (`WriteConsoleA`).
2. **Hola Mundo con Irvine32** (`HolaMundoConIrvine.asm`) - Despliegue básico con `WriteString`.
3. **Práctica 1: Ciclos Numéricos** (`Practica1.asm`) - Uso de la instrucción `LOOP` y el registro contador `ECX`.
4. **Práctica 2: Captura y Desplegado de Mensaje** (`Practica2.asm`) - Lectura de cadenas con `ReadString`.
5. **Práctica 3: Comparación y Prueba** (`Practica3.asm`) - Evaluación de banderas mediante `CMP` y `TEST`.
6. **Práctica 4: Saltos** (`Practica4.asm`) - Saltos incondicionales con `JMP`.
   * **6.1. Práctica 4.1: Mayor, Menor o Igual** (`Practica4_1.asm`) - Comparación de entradas del usuario con `JG`, `JL` y `JE`.
7. **Práctica 5: Condicionales** (`Practica5.asm`) - Implementación de bloques lógicos tipo `IF-ELSE`.
   * **7.1. Práctica 5.1: Repetir hasta ingresar 0** (`Practica5_1.asm`) - Ciclo controlado por valor centinela.
8. **Práctica 6: Decremento e Incremento** (`Practica6.asm`) - Uso de las instrucciones `INC` y `DEC`.
   * **8.1. Práctica 6.1: Control de Ocupación de un Estacionamiento** (`Practica6_1.asm`) - Menú interactivo con límites de incremento y decremento.
9. **Práctica 7: Validación de Formato** (`Practica7.asm`) - Verificación de rangos ASCII para dígitos numéricos.
10. **Práctica 8: Operaciones Aritméticas** (`Practica8.asm`) - Suma (`ADD`), resta (`SUB`), multiplicación (`MUL`) y división (`DIV`).
11. **Práctica 9: Push y Pop** (`Practica9.asm`) - Almacenamiento y recuperación de datos en la Pila (Stack).
12. **Práctica 10: Cadena con Decimal** (`Practica10.asm`) - Concatenación en consola de texto y números enteros.
13. **Práctica 11: Operaciones Lógicas** (`Practica11.asm`) - Manipulación de bits con `AND`, `OR` y `XOR`.
14. **Práctica 12: Desplazamiento y Rotación** (`Practica12.asm`) - Corrimiento de bits con `SHL`, `SHR` y `ROL`.
15. **Práctica 13: String Hexadecimal** (`Practica13.asm`) - Lectura y conversión hexadecimal mediante `ReadHex` y `WriteHex`.
16. **Práctica 14: Captura y Almacenamiento de Dato Numérico** (`Practica14.asm`) - Respaldo de registros de entrada en variables de memoria RAM.
17. **Práctica 15: Manipulación de Archivo** (`Practica15.asm`) - Creación, escritura y cierre de archivos `.txt` con `CreateOutputFile`, `WriteToFile` y `CloseFile`.